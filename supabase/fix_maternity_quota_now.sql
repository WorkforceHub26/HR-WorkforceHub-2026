-- ============================================================================
-- ปรับโควตาลาคลอดของรอบปีการลานี้ (1 ธ.ค. 2568 – 30 พ.ย. 2569) จาก 98 เป็น 90 วัน
--   ใช้ครั้งเดียว เพราะตั้งค่ากลางเป็น 90 ไปก่อนที่จะมีปุ่ม "ปรับโควตาของรอบปีนี้"
--   ปรับเฉพาะคนที่ยังเป็น 98 (คนที่ HR ตั้งรายบุคคลไว้เป็นค่าอื่นไม่ถูกทับ)
--   ต้องการค่าอื่น → เปลี่ยนเลข 90 ในบรรทัด set
-- ============================================================================
update public.employee_leave_balances
set maternity_total = 90, updated_at = now()
where year in (2026, 2569) and maternity_total = 98;

-- ตรวจผล
select maternity_total, count(*) from public.employee_leave_balances
where year in (2026, 2569) group by maternity_total order by 1;
